function currentPageName() {
  var file = window.location.pathname.split('/').pop();
  return file || 'index.html';
}

function applyPageMeta(lang) {
  var page = currentPageName();
  var table = I18N_PAGE_META[page];
  if (!table) return;

  var row = table[lang] || table[I18N_DEFAULT_LANG];
  if (!row) return;

  if (row.title) {
    document.title = row.title;
    var ogTitle = document.querySelector('meta[property="og:title"]');
    if (ogTitle) ogTitle.setAttribute('content', row.title);
    var twTitle = document.querySelector('meta[name="twitter:title"]');
    if (twTitle) twTitle.setAttribute('content', row.title);
  }

  if (row.description) {
    var desc = document.querySelector('meta[name="description"]');
    if (desc) desc.setAttribute('content', row.description);
    var ogDesc = document.querySelector('meta[property="og:description"]');
    if (ogDesc) ogDesc.setAttribute('content', row.description);
    var twDesc = document.querySelector('meta[name="twitter:description"]');
    if (twDesc) twDesc.setAttribute('content', row.description);
  }
}

function replaceIfExists(selector, value) {
  if (!value) return;
  var el = document.querySelector(selector);
  if (el) el.textContent = value;
}

function applyStaticPageCopy(lang) {
  var page = currentPageName();
  var copy = I18N_STATIC_PAGE_COPY[page];
  var nodes = I18N_STATIC_PAGE_NODES[page] || [];
  if (!copy && !nodes.length) return;

  if (copy) {
    replaceIfExists('.static-breadcrumb span:last-child', copy.breadcrumb && copy.breadcrumb[lang]);
    replaceIfExists('.static-hero h1', copy.heroTitle && copy.heroTitle[lang]);
    replaceIfExists('.static-hero p', copy.heroDesc && copy.heroDesc[lang]);
  }

  nodes.forEach(function (node) {
    replaceIfExists(node.selector, node[lang] || node[I18N_DEFAULT_LANG]);
  });
}

function applyLooseDictionaryTranslations(lang) {
  if (!document.body) return;
  var target = getDictionary(lang);

  var pairs = {};
  I18N_LANGS.forEach(function (baseLang) {
    var source = translations[baseLang] || {};
    Object.keys(source).forEach(function (k) {
      var src = source[k];
      var dst = target[k];
      if (!src || !dst || src === dst) return;
      if (!pairs[src]) pairs[src] = dst;
    });
  });

  var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  var node;
  while ((node = walker.nextNode())) {
    var parent = node.parentElement;
    if (!parent) continue;
    if (parent.closest('script,style,noscript,textarea')) continue;

    var original = node.nodeValue;
    var trimmed = original && original.trim();
    if (!trimmed) continue;
    if (pairs[trimmed]) {
      node.nodeValue = original.replace(trimmed, pairs[trimmed]);
    }
  }
}

function normalizeLang(lang) {
  const value = String(lang || '').trim().toLowerCase();
  return I18N_LANGS.includes(value) ? value : '';
}

function getLangFromUrl() {
  try {
    const params = new URLSearchParams(window.location.search || '');
    return normalizeLang(params.get('lang'));
  } catch (_) {
    return '';
  }
}

function getBrowserLang() {
  const raw = String((navigator.language || navigator.userLanguage || '')).toLowerCase();
  if (raw.startsWith('uk')) return 'uk';
  if (raw.startsWith('ru')) return 'ru';
  if (raw.startsWith('en')) return 'en';
  return I18N_DEFAULT_LANG;
}

function getDictionary(lang) {
  const resolved = lang;
  const base = translations[I18N_DEFAULT_LANG] || {};
  const dict = translations[resolved] || base;
  const merged = Object.assign({}, base, dict);

  if (lang === 'ru') {
    merged['meta.lang'] = 'ru';
  }

  return merged;
}

function withLangParam(url, lang) {
  const nextLang = normalizeLang(lang) || I18N_DEFAULT_LANG;
  let parsed;

  try {
    parsed = new URL(url, window.location.origin);
  } catch (_) {
    return url;
  }

  if (nextLang === I18N_DEFAULT_LANG) parsed.searchParams.delete('lang');
  else parsed.searchParams.set('lang', nextLang);

  return parsed.toString();
}

function syncCanonicalForLang(lang) {
  const nextLang = normalizeLang(lang) || I18N_DEFAULT_LANG;
  let canonical = document.querySelector('link[rel="canonical"]');
  if (!canonical) {
    canonical = document.createElement('link');
    canonical.setAttribute('rel', 'canonical');
    document.head.appendChild(canonical);
  }

  const baseHref = canonical.getAttribute('href') || window.location.href;
  canonical.setAttribute('href', withLangParam(baseHref, nextLang));
  return canonical.getAttribute('href');
}

